-- KFC 项目 PostgreSQL 初始化脚本
-- FastAPI/Python 后端使用。仅用于全新数据库初始化，不作为运行时 migration。
-- 表间 ID 只表示逻辑关联，不创建数据库外键约束。

BEGIN;
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

DO $$ BEGIN
  CREATE TYPE "access_link_history_status_enum" AS ENUM ('UNUSED','PROCESSING','PICKING_UP','FAILED','COMPLETED');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE "fulfillment_stage_enum" AS ENUM ('SUBMITTED','PREPARING','READY','COMPLETED','FAILED','UNKNOWN');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS "schema_migrations" (
  "version" varchar(120) PRIMARY KEY,
  "applied_at" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "users" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "username" varchar(80) NOT NULL,
  "password_hash" varchar(255) NOT NULL,
  "enabled" boolean NOT NULL DEFAULT true,
  "last_login_at" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_users_username" UNIQUE ("username")
);

-- 请使用 tools/create_admin.py 创建独立管理员账号，不预设密码哈希。

CREATE TABLE IF NOT EXISTS "admin_sessions" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" uuid NOT NULL,
  "token_hash" char(64) NOT NULL,
  "expires_at" timestamptz NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "last_seen_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_admin_sessions_token_hash" UNIQUE ("token_hash")
);

CREATE TABLE IF NOT EXISTS "kfc_tickets" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" varchar(120) NOT NULL,
  "ticket" text NOT NULL,
  "user_code" varchar(160) NOT NULL,
  "phone" varchar(40) NOT NULL DEFAULT '',
  "open_id" varchar(200) NOT NULL DEFAULT '',
  "device_id" varchar(200) NOT NULL DEFAULT '',
  "cookie" text NOT NULL DEFAULT '',
  "kbck" varchar(255) NOT NULL DEFAULT '',
  "auth_state" jsonb NOT NULL DEFAULT '{}'::jsonb,
  "captured_at" timestamptz,
  "enabled" boolean NOT NULL DEFAULT true,
  "last_synced_at" timestamptz,
  "remark" text NOT NULL DEFAULT '',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "kfc_sessions" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "phone" varchar(160) NOT NULL,
  "session_id" varchar(200) NOT NULL,
  "expires_at" timestamptz NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "platforms" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" varchar(120) NOT NULL,
  "code" varchar(40) NOT NULL,
  "enabled" boolean NOT NULL DEFAULT true,
  "remark" text NOT NULL DEFAULT '',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_platform_code" UNIQUE ("code")
);

CREATE TABLE IF NOT EXISTS "platform_accounts" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "platform_id" uuid NOT NULL,
  "name" varchar(120) NOT NULL,
  "identifier" varchar(160) NOT NULL,
  "enabled" boolean NOT NULL DEFAULT true,
  "remark" text NOT NULL DEFAULT '',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_platform_account_identifier" UNIQUE ("platform_id","identifier")
);

CREATE TABLE IF NOT EXISTS "products" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" varchar(120) NOT NULL,
  "description" text NOT NULL DEFAULT '',
  "image_url" text,
  "parent_link_id" varchar(120) NOT NULL DEFAULT 'PENDING-KFC-LINK-ID',
  "spec_link_ids" jsonb NOT NULL DEFAULT '[]'::jsonb,
  "condiment_link_ids" jsonb NOT NULL DEFAULT '[]'::jsonb,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "kfc_product_name_mappings" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "kfc_product_name" varchar(500) NOT NULL,
  "product_id" uuid NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_kfc_product_name_mapping" UNIQUE ("kfc_product_name")
);

CREATE TABLE IF NOT EXISTS "product_options" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "product_id" uuid NOT NULL,
  "group_no" integer NOT NULL,
  "group_name" varchar(50) NOT NULL,
  "select_count" integer NOT NULL DEFAULT 1,
  "option_name" varchar(120) NOT NULL,
  "image_url" text,
  "sort" integer NOT NULL DEFAULT 0,
  CONSTRAINT "UQ_product_option_name" UNIQUE ("product_id", "group_no", "option_name"),
  CONSTRAINT "CHK_product_option_group_no" CHECK ("group_no" > 0),
  CONSTRAINT "CHK_product_option_select_count" CHECK ("select_count" > 0)
);

CREATE TABLE IF NOT EXISTS "taobao_product_prices" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "search_keyword" varchar(200) NOT NULL DEFAULT '',
  "shop_name" varchar(255) NOT NULL,
  "product_url" varchar(1000) NOT NULL,
  "item_name" varchar(500) NOT NULL,
  "price" numeric(12,2) NOT NULL,
  "scraped_at" timestamptz NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_taobao_product_price_item" UNIQUE ("product_url", "item_name", "search_keyword"),
  CONSTRAINT "CHK_taobao_product_price_nonnegative" CHECK ("price" >= 0)
);

CREATE TABLE IF NOT EXISTS "taobao_search_keywords" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "keyword" varchar(200) NOT NULL,
  "url" varchar(2000) NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CHK_taobao_search_keyword_not_blank" CHECK (length(btrim("keyword")) > 0),
  CONSTRAINT "CHK_taobao_search_url_not_blank" CHECK (length(btrim("url")) > 0)
);

CREATE TABLE IF NOT EXISTS "taobao_browser_sessions" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "profile_name" varchar(80) NOT NULL,
  "cookies" jsonb NOT NULL DEFAULT '[]'::jsonb,
  "origins" jsonb NOT NULL DEFAULT '[]'::jsonb,
  "session_storage" jsonb NOT NULL DEFAULT '{}'::jsonb,
  "captured_url" varchar(2000) NOT NULL DEFAULT '',
  "captured_title" varchar(500) NOT NULL DEFAULT '',
  "captured_at" timestamptz NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_taobao_browser_session_profile" UNIQUE ("profile_name"),
  CONSTRAINT "CHK_taobao_browser_session_cookies" CHECK (jsonb_typeof("cookies") = 'array'),
  CONSTRAINT "CHK_taobao_browser_session_origins" CHECK (jsonb_typeof("origins") = 'array'),
  CONSTRAINT "CHK_taobao_browser_session_storage" CHECK (jsonb_typeof("session_storage") = 'object')
);

CREATE TABLE IF NOT EXISTS "coupon_import_batches" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" varchar(120) NOT NULL,
  "platform_id" uuid NOT NULL,
  "account_id" uuid NOT NULL,
  "product_id" uuid,
  "total_rows" integer NOT NULL,
  "success_count" integer NOT NULL DEFAULT 0,
  "failed_count" integer NOT NULL DEFAULT 0,
  "imported_at" timestamptz NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CHK_coupon_batches_counts" CHECK (
    "total_rows" >= 0 AND "success_count" >= 0 AND "failed_count" >= 0
    AND "success_count" + "failed_count" <= "total_rows"
  )
);

CREATE TABLE IF NOT EXISTS "coupons" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "coupon_code" varchar(255) NOT NULL,
  "local_status" varchar(20) NOT NULL DEFAULT 'wait',
  "product_name" varchar(500) NOT NULL DEFAULT '',
  "kfc_status" varchar(20),
  "platform_id" uuid NOT NULL,
  "account_id" uuid NOT NULL,
  "product_id" uuid,
  "batch_id" uuid NOT NULL,
  "imported_at" timestamptz NOT NULL,
  "last_seen_at" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_coupon_platform_code" UNIQUE ("platform_id","coupon_code")
);

CREATE TABLE IF NOT EXISTS "access_links" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "public_id" varchar(16) NOT NULL,
  "status" varchar(20) NOT NULL DEFAULT 'UNUSED',
  "coupon_code" varchar(255),
  "product_id" uuid,
  "platform_id" uuid,
  "account_id" uuid,
  "imported_at" timestamptz,
  "internal_locked_at" timestamptz,
  "coupon_cart_id" varchar(255),
  "cart_id" varchar(255),
  "pickup_type" smallint NOT NULL DEFAULT 2 CHECK ("pickup_type" IN (1,2)),
  "store_image_url" text,
  "coupon_applied_at" timestamptz,
  "redemption_status" varchar(32),
  "redemption_payload" jsonb,
  "store_code" varchar(64) GENERATED ALWAYS AS (NULLIF("redemption_payload" ->> 'storeCode','')) STORED,
  "redemption_error" text NOT NULL DEFAULT '',
  "redemption_started_at" timestamptz,
  "redemption_finished_at" timestamptz,
  "ordered_at" timestamptz,
  "completed_at" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_access_link_public_id" UNIQUE ("public_id"),
  CONSTRAINT "CHK_access_link_public_id_length" CHECK (char_length("public_id")=16),
  CONSTRAINT "CHK_access_link_status" CHECK ("status" IN ('UNUSED','PROCESSING','PICKING_UP','FAILED','COMPLETED')),
  CONSTRAINT "CHK_access_link_redemption_status" CHECK (
    "redemption_status" IS NULL OR
    "redemption_status" IN ('WAITING','PROCESSING','CART_CREATED','COUPON_APPLIED','COMPLETED','FAILED','UNKNOWN')
  )
);

CREATE TABLE IF NOT EXISTS "coupon_assignment_logs" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "access_link_id" bigint NOT NULL,
  "coupon_id" bigint NOT NULL,
  "visitor_ip" varchar(64) NOT NULL,
  "assigned_at" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "order_confirmation_logs" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "public_id" varchar(16) NOT NULL,
  "visitor_ip" varchar(64) NOT NULL,
  "store_id" varchar(64) NOT NULL,
  "store_address" text NOT NULL,
  "production_info" jsonb NOT NULL DEFAULT '[]'::jsonb,
  "result" jsonb,
  "confirmed_at" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "access_link_status_history" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "access_link_id" bigint NOT NULL,
  "from_status" "access_link_history_status_enum",
  "to_status" "access_link_history_status_enum" NOT NULL,
  "source" varchar(40) NOT NULL,
  "reason" text NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CHK_access_link_history_source" CHECK ("source" IN ('system','admin'))
);

CREATE TABLE IF NOT EXISTS "orders" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "access_link_public_id" varchar(16) NOT NULL,
  "idempotency_key" varchar(128) NOT NULL,
  "external_order_id" varchar(128),
  "store_snapshot" jsonb NOT NULL,
  "items_snapshot" jsonb NOT NULL,
  "stage" "fulfillment_stage_enum" NOT NULL,
  "status_code" varchar(32) NOT NULL DEFAULT '',
  "status_name" varchar(80) NOT NULL DEFAULT '',
  "queue_number" varchar(40),
  "pickup_code" varchar(40),
  "raw_status" jsonb,
  "submit_response" jsonb,
  "result_unknown" boolean NOT NULL DEFAULT false,
  "last_queried_at" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_orders_access_link_public_id" UNIQUE ("access_link_public_id"),
  CONSTRAINT "UQ_orders_idempotency_key" UNIQUE ("idempotency_key"),
  CONSTRAINT "CHK_orders_items_snapshot_array" CHECK (jsonb_typeof("items_snapshot")='array'),
  CONSTRAINT "CHK_orders_store_snapshot_object" CHECK (jsonb_typeof("store_snapshot")='object')
);

CREATE TABLE IF NOT EXISTS "audit_logs" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "actor_id" varchar(120),
  "action" varchar(120) NOT NULL,
  "entity_type" varchar(80) NOT NULL,
  "entity_id" varchar(128) NOT NULL,
  "details" jsonb NOT NULL DEFAULT '{}'::jsonb,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "IDX_admin_sessions_expires_at" ON "admin_sessions" ("expires_at");
CREATE INDEX IF NOT EXISTS "IDX_admin_sessions_user_id" ON "admin_sessions" ("user_id");
CREATE INDEX IF NOT EXISTS "IDX_kfc_tickets_enabled" ON "kfc_tickets" ("enabled","createdAt" DESC);
CREATE UNIQUE INDEX IF NOT EXISTS "UQ_kfc_sessions_phone" ON "kfc_sessions" ("phone");
CREATE INDEX IF NOT EXISTS "IDX_kfc_sessions_expires_at" ON "kfc_sessions" ("expires_at");
CREATE INDEX IF NOT EXISTS "IDX_platform_accounts_platform_id" ON "platform_accounts" ("platform_id");
CREATE INDEX IF NOT EXISTS "IDX_kfc_product_name_mapping_product" ON "kfc_product_name_mappings" ("product_id");
CREATE INDEX IF NOT EXISTS "IDX_product_options_product_order" ON "product_options" ("product_id","group_no","sort","id");
CREATE INDEX IF NOT EXISTS "IDX_taobao_product_prices_scraped_at" ON "taobao_product_prices" ("scraped_at" DESC,"id" DESC);
CREATE INDEX IF NOT EXISTS "IDX_taobao_product_prices_shop_name" ON "taobao_product_prices" ("shop_name");
CREATE INDEX IF NOT EXISTS "IDX_taobao_product_prices_keyword_scraped_at" ON "taobao_product_prices" ("search_keyword", "scraped_at");
CREATE INDEX IF NOT EXISTS "IDX_taobao_browser_sessions_captured_at" ON "taobao_browser_sessions" ("captured_at" DESC,"id" DESC);
CREATE INDEX IF NOT EXISTS "IDX_coupon_batches_product_imported" ON "coupon_import_batches" ("product_id","imported_at" DESC);
CREATE INDEX IF NOT EXISTS "IDX_coupon_batches_platform_account" ON "coupon_import_batches" ("platform_id","account_id");
CREATE INDEX IF NOT EXISTS "IDX_coupon_product_imported_at" ON "coupons" ("product_id","imported_at" DESC);
CREATE INDEX IF NOT EXISTS "IDX_coupon_imported_at" ON "coupons" ("imported_at" DESC);
CREATE INDEX IF NOT EXISTS "IDX_coupon_last_seen_at" ON "coupons" ("last_seen_at");
CREATE INDEX IF NOT EXISTS "IDX_coupon_batch_id" ON "coupons" ("batch_id");
CREATE INDEX IF NOT EXISTS "IDX_coupon_account_id" ON "coupons" ("account_id");
CREATE INDEX IF NOT EXISTS "IDX_coupon_allocation" ON "coupons" ("kfc_status","local_status","product_id","createdAt",id);
CREATE INDEX IF NOT EXISTS "IDX_access_links_product_status" ON "access_links" ("product_id","status");
CREATE INDEX IF NOT EXISTS "IDX_access_links_imported_at" ON "access_links" ("imported_at" DESC);
CREATE INDEX IF NOT EXISTS "IDX_access_links_redemption_queue" ON "access_links" ("redemption_status","updatedAt",id);
CREATE INDEX IF NOT EXISTS "IDX_coupon_assignment_logs_access_link" ON "coupon_assignment_logs" ("access_link_id","assigned_at" DESC);
CREATE INDEX IF NOT EXISTS "IDX_coupon_assignment_logs_coupon" ON "coupon_assignment_logs" ("coupon_id","assigned_at" DESC);
CREATE INDEX IF NOT EXISTS "IDX_order_confirmation_logs_public_id" ON "order_confirmation_logs" ("public_id","confirmed_at" DESC);
CREATE INDEX IF NOT EXISTS "IDX_access_link_history_link_created" ON "access_link_status_history" ("access_link_id","createdAt" DESC);
CREATE INDEX IF NOT EXISTS "IDX_orders_external_order_id" ON "orders" ("external_order_id") WHERE "external_order_id" IS NOT NULL;
CREATE INDEX IF NOT EXISTS "IDX_orders_stage_updated" ON "orders" ("stage","updatedAt" DESC);
CREATE INDEX IF NOT EXISTS "IDX_audit_logs_entity" ON "audit_logs" ("entity_type","entity_id","createdAt" DESC);

COMMIT;
