-- Optimization foundation: recoverable coupon application, persistent admin sessions,
-- KFC sync freshness and explicit product-name mapping.

CREATE TABLE IF NOT EXISTS schema_migrations (
  version varchar(120) PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS admin_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  token_hash char(64) NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT UQ_admin_sessions_token_hash UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS IDX_admin_sessions_expires_at ON admin_sessions (expires_at);
CREATE INDEX IF NOT EXISTS IDX_admin_sessions_user_id ON admin_sessions (user_id);

ALTER TABLE coupons ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;
UPDATE coupons SET last_seen_at = COALESCE(last_seen_at, imported_at, "updatedAt", "createdAt");
CREATE INDEX IF NOT EXISTS IDX_coupon_last_seen_at ON coupons (last_seen_at);

CREATE TABLE IF NOT EXISTS kfc_product_name_mappings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kfc_product_name varchar(500) NOT NULL,
  product_id uuid NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT UQ_kfc_product_name_mapping UNIQUE (kfc_product_name)
);
CREATE INDEX IF NOT EXISTS IDX_kfc_product_name_mapping_product ON kfc_product_name_mappings (product_id);

CREATE TABLE IF NOT EXISTS coupon_application_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  access_link_id bigint NOT NULL,
  coupon_id bigint NOT NULL,
  coupon_code varchar(255) NOT NULL,
  status varchar(32) NOT NULL,
  cart_id varchar(255),
  upstream_code varchar(120),
  error_message text NOT NULL DEFAULT '',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT CHK_coupon_application_attempt_status CHECK (
    status IN ('PROCESSING','UPSTREAM_SUCCEEDED','COMPLETED','FAILED','UNKNOWN')
  )
);
CREATE INDEX IF NOT EXISTS IDX_coupon_application_attempt_link
  ON coupon_application_attempts (access_link_id, "createdAt" DESC, id DESC);
CREATE INDEX IF NOT EXISTS IDX_coupon_application_attempt_coupon
  ON coupon_application_attempts (coupon_id, "createdAt" DESC, id DESC);
