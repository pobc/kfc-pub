-- Preserve existing confirmation records when upgrading an installed database.
DO $$ BEGIN
  IF to_regclass('public.order_confirmation_logs') IS NULL
     AND to_regclass('public.product_confirmation_logs') IS NOT NULL THEN
    ALTER TABLE product_confirmation_logs RENAME TO order_confirmation_logs;
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS order_confirmation_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id varchar(16) NOT NULL,
  visitor_ip varchar(64) NOT NULL,
  store_id varchar(64) NOT NULL,
  store_address text NOT NULL,
  confirmed_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE order_confirmation_logs ADD COLUMN IF NOT EXISTS result jsonb;
ALTER INDEX IF EXISTS "IDX_product_confirmation_logs_public_id" RENAME TO "IDX_order_confirmation_logs_public_id";
CREATE INDEX IF NOT EXISTS "IDX_order_confirmation_logs_public_id" ON order_confirmation_logs(public_id,confirmed_at DESC);
ALTER TABLE access_links ADD COLUMN IF NOT EXISTS pickup_type smallint NOT NULL DEFAULT 2 CHECK (pickup_type IN (1,2));
UPDATE access_links SET pickup_type=(redemption_payload->>'packType')::smallint
WHERE redemption_payload->>'packType' IN ('1','2');
ALTER TABLE access_links ADD COLUMN IF NOT EXISTS cart_id varchar(255);
UPDATE access_links SET cart_id=coupon_cart_id WHERE cart_id IS NULL AND coupon_cart_id IS NOT NULL;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS submit_response jsonb;
